/** Integer amount in euro cents. Movement amounts are always positive; the sign comes from `type`. */
export type Cents = number;
/** Local calendar date 'YYYY-MM-DD', without time or timezone. */
export type ISODate = string;
/** Calendar month 'YYYY-MM'. */
export type YearMonth = string;
/** ISO timestamp. Only used for record metadata, never for the date of a movement. */
export type Timestamp = string;

export type TxType = 'expense' | 'income';

interface EntityMeta {
  id: string;
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

export interface Account extends EntityMeta {
  name: string;
  color: string;
  /** Can be negative. */
  initialBalance: Cents;
  /** "Cuenta para ahorro": its movements count towards total savings. */
  countsForSavings: boolean;
  order: number;
}

export interface Group extends EntityMeta {
  name: string;
  color: string;
  order: number;
}

export interface Category extends EntityMeta {
  name: string;
  color: string;
  /** An emoji. */
  icon: string;
  type: TxType;
  /** Required for expense categories, always null for income categories. */
  groupId: string | null;
  order: number;
}

export interface Tag extends EntityMeta {
  name: string;
  order: number;
}

export interface Transaction extends EntityMeta {
  type: TxType;
  amount: Cents;
  date: ISODate;
  accountId: string;
  categoryId: string;
  title: string | null;
  tagIds: string[];
  /** Set when the movement was generated by a recurring rule. */
  recurringRuleId: string | null;
  /** Month of the rule this movement belongs to. */
  recurringMonth: YearMonth | null;
}

export interface RecurringRule extends EntityMeta {
  type: TxType;
  amount: Cents;
  /** 1–31. Months without that day use their last day. */
  dayOfMonth: number;
  accountId: string;
  categoryId: string;
  title: string | null;
  tagIds: string[];
  startMonth: YearMonth;
  endMonth: YearMonth | null;
}

/**
 * Records that a rule has already been generated for a month, even if the movement was later deleted.
 * Keeps generation idempotent and stops deleted movements from coming back.
 */
export interface RecurringOccurrence {
  ruleId: string;
  month: YearMonth;
  transactionId: string;
  createdAt: Timestamp;
}

export interface Setting {
  key: string;
  value: unknown;
}

/** Fields the user provides; id and timestamps are filled in by the repositories. */
export type Draft<T extends EntityMeta> = Omit<T, keyof EntityMeta>;

export type AccountDraft = Omit<Draft<Account>, 'order'>;
export type GroupDraft = Omit<Draft<Group>, 'order'>;
export type CategoryDraft = Omit<Draft<Category>, 'order'>;
export type TransactionDraft = Draft<Transaction>;
export type RecurringRuleDraft = Draft<RecurringRule>;

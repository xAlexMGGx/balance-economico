import type { BackupData } from '../../domain/backup';
import { db } from '../db';
import { recurringRepo } from './recurring';
import { settingsRepo } from './settings';

const allTables = () => [
  db.accounts,
  db.groups,
  db.categories,
  db.tags,
  db.transactions,
  db.recurringRules,
  db.recurringOccurrences,
  db.settings,
];

export const backupRepo = {
  /** Every table, read in one consistent snapshot. */
  async exportData(): Promise<BackupData> {
    return db.transaction('r', allTables(), async () => {
      const [accounts, groups, categories, tags, transactions, recurringRules, recurringOccurrences, settings] =
        await Promise.all([
          db.accounts.toArray(),
          db.groups.toArray(),
          db.categories.toArray(),
          db.tags.toArray(),
          db.transactions.toArray(),
          db.recurringRules.toArray(),
          db.recurringOccurrences.toArray(),
          db.settings.toArray(),
        ]);
      return { accounts, groups, categories, tags, transactions, recurringRules, recurringOccurrences, settings };
    });
  },

  /**
   * Replaces all data with a backup's. All or nothing: if anything fails, the current data stays.
   * `data` must come from `parseBackup`, which has already validated it.
   */
  async replaceAll(data: BackupData, exportedAt: string): Promise<void> {
    await db.transaction('rw', allTables(), async () => {
      await Promise.all(allTables().map((table) => table.clear()));
      await db.accounts.bulkAdd(data.accounts);
      await db.groups.bulkAdd(data.groups);
      await db.categories.bulkAdd(data.categories);
      await db.tags.bulkAdd(data.tags);
      await db.transactions.bulkAdd(data.transactions);
      await db.recurringRules.bulkAdd(data.recurringRules);
      await db.recurringOccurrences.bulkAdd(data.recurringOccurrences);
      await db.settings.bulkAdd(data.settings);
      // The data is now exactly that copy, so the last backup is the copy itself.
      await settingsRepo.set('lastBackupAt', exportedAt);
    });
    // An old copy may be missing months its rules should have generated by now.
    await recurringRepo.generateDue();
  },

  markExported(at: Date): Promise<void> {
    return settingsRepo.set('lastBackupAt', at.toISOString());
  },

  snoozeReminder(until: string): Promise<void> {
    return settingsRepo.set('backupReminderSnoozedUntil', until);
  },
};
